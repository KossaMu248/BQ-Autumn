const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const window={};
const context=vm.createContext({window});
for(const file of ['illustrated-neighbourhood','autumn-quests'])vm.runInContext(fs.readFileSync(`js/${file}.js`,'utf8'),context);
const world=window.BearlyNeighbourhood;
assert.equal(world.nearestEntrance(17700).key,'library');
assert.equal(world.nearestEntrance(1500),null);
assert.equal(world.nearestEntrance(18000),null);
for(const b of world.scenes.filter(world.canVisit))assert.equal(world.nearestEntrance(world.entrance(b).x).key,b.key);
for(const role of ['metro','library','cafe'])assert.equal(world.scenes.filter(b=>b.role===role).length,1);
assert.equal(new Set(world.scenes.map(b=>b.key)).size,world.scenes.length);
const p=world.placement(world.scenes[0],x=>400+x*.2);
assert.ok(p.samples.every(q=>q.y>p.foot));
assert.equal(world.placement(world.scenes[0],x=>x<1500?400:null),null);
const walk=(t)=>world.walkingAt(t,0,600,25,4);
assert.equal(walk(2).x,0);assert.equal(walk(16).x,300);assert.equal(walk(30).paused,true);assert.equal(walk(44).x,300);assert.equal(walk(44).flip,true);
let saved=null;const storage={getItem:()=>saved,setItem:(key,value)=>{saved=value}};
const q=window.BearlyQuests.create(storage);
q.act('deliver');q.act('repair');q.act('buoy',0);q.act('return');
assert.equal(q.snapshot().boatReady,false);assert.equal(q.snapshot().buoys.length,0);assert.equal(q.snapshot().voyage,false);
q.act('lunch');q.act('kit');assert.equal(q.snapshot().lunch,true);assert.equal(q.snapshot().kit,true);
q.act('deliver');assert.equal(q.snapshot().lunch,false);assert.equal(q.snapshot().boatReady,false);
q.act('repair');assert.equal(q.snapshot().kit,false);assert.equal(q.snapshot().boatReady,true);
q.act('buoy',0);q.act('buoy',0);q.act('buoy',99);q.act('return');assert.equal(q.snapshot().buoys.length,1);assert.equal(q.snapshot().voyage,false);
q.act('buoy',1);q.act('buoy',2);q.act('return');assert.equal(q.snapshot().voyage,true);
q.act('garden');assert.equal(q.snapshot().garden,false);
for(const i of [0,1,2])q.act('seed',i);q.act('garden');assert.equal(q.snapshot().garden,true);
assert.deepEqual(JSON.parse(JSON.stringify(window.BearlyQuests.create(storage).snapshot())),JSON.parse(JSON.stringify(q.snapshot())));
const copy=q.snapshot();copy.buoys.length=0;assert.equal(q.snapshot().buoys.length,3);
const blocked=window.BearlyQuests.create({getItem(){throw Error('storage denied')},setItem(){throw Error('storage denied')}});assert.equal(blocked.act('lunch').lunch,true);
console.log('Placement and quest checks passed: access, terrain, walking, inventory requirements, boat unlock, buoy/seed objectives, persistence and unavailable storage.');
